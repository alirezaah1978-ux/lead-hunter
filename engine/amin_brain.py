def is_amin_mode():
    if os.path.exists(AMIN_STATE_PATH):
        try:
            return bool(json.load(open(AMIN_STATE_PATH, encoding="utf-8")).get("active", False))
        except Exception:
            pass
    return False

def set_amin_mode(active: bool):
    os.makedirs(OUT, exist_ok=True)
    json.dump({"active": bool(active), "updated_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S")},
              open(AMIN_STATE_PATH, "w", encoding="utf-8"), ensure_ascii=False)

def search_archive(query, top_k=3):
    results = []
    tokens = [w for w in re.split(r"[\s،,؟?!.]+", query.strip()) if len(w) >= 2]
    stop = {"من", "تو", "که", "در", "به", "از", "رو", "را", "این", "اون", "یک", "یه", "با", "برای", "چیه", "چی", "چطور", "کنم", "بگو", "محمد", "امین", "حیدری", "هستی"}
    tokens = [t for t in tokens if t not in stop]
    if not tokens:
        tokens = ["دیوار", "فروش", "آگهی"]

    # ۱. جست‌وجو در پست‌های اینستاگرام
    if os.path.exists(IG_PATH):
        try:
            ig_posts = json.load(open(IG_PATH, encoding="utf-8"))
            for ip in ig_posts:
                cap = ip.get("caption") or ""
                sc = sum(12 for tk in tokens if tk in cap)
                if sc > 0:
                    results.append((sc + 5, f"📸 [ریلز اینستاگرام {ip['code']}]", cap))
        except Exception:
            pass

    # ۲. جست‌وجو در ۱۴۶۵ پست تلگرام
    if os.path.exists(ARCHIVE_PATH):
        try:
            data = json.load(open(ARCHIVE_PATH, encoding="utf-8"))
            for p in data.get("posts", []):
                txt = p.get("text") or ""
                if len(txt) < 35:
                    continue
                sc = sum(10 + min(txt.count(tk) * 2, 6) for tk in tokens if tk in txt)
                if sc > 0:
                    sc += min(len(txt) / 120.0, 6.0)
                    results.append((sc, f"📢 [تلگرام #{p['id']} | {p['date'][:10]}]", txt))
        except Exception:
            pass

    results.sort(key=lambda x: x[0], reverse=True)
    out = []
    seen = set()
    for sc, label, txt in results:
        clean = re.sub(r"\s+", " ", txt).strip()
        key = clean[:45]
        if key in seen:
            continue
        seen.add(key)
        out.append((label, clean[:220]))
        if len(out) >= top_k:
            break
    return out

