# ۳. موتور جست‌وجو در آرشیو ۱۴۶۵ پست واقعی محمد امین حیدری
# ══════════════════════════════════════════════════════════════════════════════
def search_archive(query, top_k=4):
    if not os.path.exists(ARCHIVE_PATH):
        return []
    data = json.load(open(ARCHIVE_PATH, encoding="utf-8"))
    posts = data.get("posts", [])
    tokens = [w for w in re.split(r"[\s،,؟?!.]+", query.strip()) if len(w) >= 2]
    stop = {"من", "تو", "که", "در", "به", "از", "رو", "را", "این", "اون", "یک", "یه", "با", "برای", "چیه", "چی", "چطور", "کنم", "بگو", "محمد", "امین", "حیدری", "هستی"}
    tokens = [t for t in tokens if t not in stop]
    if not tokens:
        tokens = ["دیوار", "فروش", "آگهی"]

    scored = []
    for p in posts:
        txt = p.get("text") or ""
        if len(txt) < 35:
            continue
        score = 0
        for tk in tokens:
            if tk in txt:
                score += 10 + min(txt.count(tk) * 3, 9)
        if score > 0:
            # امتیاز بیشتر به پست‌های آموزشی بلندتر
            score += min(len(txt) / 100.0, 8.0)
            scored.append((score, p))

    scored.sort(key=lambda x: (x[0], x[1]["id"]), reverse=True)
    results = []
    seen_prefixes = set()
    for sc, p in scored:
        pref = p["text"][:50]
        if pref in seen_prefixes:
            continue
        seen_prefixes.add(pref)
        results.append(p)
        if len(results) >= top_k:
            break
    return results

